"""Subset Noto Serif/Sans CJK KR to the page's characters that Google Fonts'
Noto Serif KR and Noto Sans KR do not serve (e.g. 㐎 in 韓㐎), so visitors
without a CJK font see them in the same design instead of a random fallback.

Usage: uv run --with fonttools --with brotli scripts/rare-glyphs.py
Reads the page sources under src/ and index.html, the live Google Fonts CSS
for the coverage, and the Noto CJK .ttc files installed on this machine
(Noto CJK, SIL OFL 1.1). Writes public/fonts/rare-*.woff2 and
design/rare-glyphs.css, which adds them to the Google families for just those
characters.
"""
import re
import sys
import urllib.request
from pathlib import Path

from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTCollection

WEB = Path(__file__).resolve().parent.parent
NOTO = Path("/usr/share/fonts/opentype/noto")
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/130 Safari/537.36"
# (output, collection, Google family, CSS weights)
FACES = [
    ("rare-serif-500", "NotoSerifCJK-Medium.ttc", "Noto+Serif+KR", "100 500"),
    ("rare-serif-700", "NotoSerifCJK-Bold.ttc", "Noto+Serif+KR", "600 800"),
    ("rare-serif-900", "NotoSerifCJK-Black.ttc", "Noto+Serif+KR", "900"),
    ("rare-sans-400", "NotoSansCJK-Regular.ttc", "Noto+Sans+KR", "100 500"),
    ("rare-sans-700", "NotoSansCJK-Bold.ttc", "Noto+Sans+KR", "600 900"),
]
CJK = re.compile(r"[⺀-鿿豈-﫿\U00020000-\U0003134f]")


def page_chars():
    chars = set()
    for p in [WEB / "index.html", *WEB.joinpath("src").rglob("*")]:
        if p.suffix in (".html", ".svelte", ".js") and not p.name.endswith(".test.js"):
            chars |= set(CJK.findall(p.read_text(encoding="utf-8")))
    return chars


def google_ranges(family):
    req = urllib.request.Request(f"https://fonts.googleapis.com/css2?family={family}", headers={"User-Agent": UA})
    css = urllib.request.urlopen(req).read().decode()
    ranges = []
    for block in re.findall(r"unicode-range:\s*([^;]+);", css):
        for part in block.split(","):
            a, _, b = part.strip()[2:].partition("-")
            ranges.append((int(a, 16), int(b or a, 16)))
    return ranges


def korean_font(ttc):
    for f in TTCollection(str(NOTO / ttc)).fonts:
        if "CJK KR" in f["name"].getDebugName(1):
            return f
    sys.exit(f"no KR face in {ttc}")


def main():
    chars = page_chars()
    coverage = {}
    written = set()
    css = ["/* Generated by scripts/rare-glyphs.py: characters of the page that Google's",
           "   Noto Serif KR / Noto Sans KR do not serve, from Noto CJK KR (SIL OFL 1.1). */"]
    for out, ttc, family, weight in FACES:
        if family not in coverage:
            coverage[family] = google_ranges(family)
        missing = sorted(c for c in chars if not any(a <= ord(c) <= b for a, b in coverage[family]))
        font = korean_font(ttc)
        missing = [c for c in missing if ord(c) in font.getBestCmap()]
        written |= set(missing)
        opts = Options()
        opts.flavor = "woff2"
        opts.layout_features = ["*"]
        opts.name_IDs = ["*"]  # keeps the OFL notice (IDs 13, 14)
        sub = Subsetter(opts)
        sub.populate(text="".join(missing))
        sub.subset(font)
        font.flavor = "woff2"
        font.save(WEB / "public" / "fonts" / f"{out}.woff2")
        ranges = ", ".join(f"U+{ord(c):X}" for c in missing)
        css.append(f"@font-face {{\n  font-family: '{family.replace('+', ' ')}';\n  font-weight: {weight};\n"
                   f"  font-display: swap;\n  src: url('/fonts/{out}.woff2') format('woff2');\n"
                   f"  unicode-range: {ranges};\n}}")
    (WEB / "design" / "rare-glyphs.css").write_text("\n".join(css) + "\n", encoding="utf-8")
    print("".join(sorted(written)))


if __name__ == "__main__":
    main()

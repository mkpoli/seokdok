"""Generate crates/seokdok-core/src/old_jamo.rs: every Hangul conjoining jamo
(U+1100–11FF, U+A960–A97F, U+D7B0–D7FF) as the sequence of letters typed to
build it, read off its Unicode character name, plus the compatibility jamo
that display each one alone (from the compatibility decompositions).

Usage: uv run tools/gen_old_jamo.py
Source: the Unicode Character Database as shipped with Python's unicodedata.
"""
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "crates" / "seokdok-core" / "src" / "old_jamo.rs"

CONS = {
    "KIYEOK": "ㄱ", "NIEUN": "ㄴ", "TIKEUT": "ㄷ", "RIEUL": "ㄹ", "MIEUM": "ㅁ", "PIEUP": "ㅂ",
    "SIOS": "ㅅ", "IEUNG": "ㅇ", "CIEUC": "ㅈ", "CHIEUCH": "ㅊ", "KHIEUKH": "ㅋ", "THIEUTH": "ㅌ",
    "PHIEUPH": "ㅍ", "HIEUH": "ㅎ", "YESIEUNG": "ㆁ", "YEORINHIEUH": "ㆆ", "PANSIOS": "ㅿ",
    # Sibilants of Chinese transcription have keys of their own (Shift+Z…N).
    "CHITUEUMSIOS": "ᄼ", "CEONGCHIEUMSIOS": "ᄾ", "CHITUEUMCIEUC": "ᅎ",
    "CEONGCHIEUMCIEUC": "ᅐ", "CHITUEUMCHIEUCH": "ᅔ", "CEONGCHIEUMCHIEUCH": "ᅕ",
}
# Doubles with a key of their own (Shift+Q W E R T); other doubles are typed twice.
KEYED_DOUBLE = {"KIYEOK": "ㄲ", "TIKEUT": "ㄸ", "PIEUP": "ㅃ", "SIOS": "ㅆ", "CIEUC": "ㅉ"}
VOWELS = {
    "A": "ㅏ", "AE": "ㅐ", "YA": "ㅑ", "YAE": "ㅒ", "EO": "ㅓ", "E": "ㅔ", "YEO": "ㅕ", "YE": "ㅖ",
    "O": "ㅗ", "YO": "ㅛ", "U": "ㅜ", "YU": "ㅠ", "EU": "ㅡ", "I": "ㅣ", "ARAEA": "ㆍ",
}
COMPOUND_VOWELS = {
    "WA": "ㅗㅏ", "WAE": "ㅗㅐ", "OE": "ㅗㅣ", "WEO": "ㅜㅓ", "WE": "ㅜㅔ", "WI": "ㅜㅣ", "YI": "ㅡㅣ",
    "ARAEAE": "ㆍㅣ",
}


def consonant(word):
    if word in CONS:
        return CONS[word]
    if word.startswith("KAPYEOUN"):
        return consonant(word[len("KAPYEOUN"):]) + "ㅇ"
    if word.startswith("SSANG"):
        rest = word[len("SSANG"):]
        if rest in KEYED_DOUBLE:
            return KEYED_DOUBLE[rest]
        c = consonant(rest)
        return c + c
    for p in ("CHITUEUM", "CEONGCHIEUM"):
        if word.startswith(p + "SSANG"):
            c = consonant(p + word[len(p) + 5:])
            return c + c
    raise KeyError(word)


def vowel(word):
    if word in VOWELS:
        return VOWELS[word]
    if word in COMPOUND_VOWELS:
        return COMPOUND_VOWELS[word]
    if word.startswith("SSANG"):
        v = vowel(word[5:])
        return v + v
    raise KeyError(word)


def main():
    tables = {"CHO": [], "JUNG": [], "JONG": []}
    skipped = []
    for lo, hi in ((0x1100, 0x11FF), (0xA960, 0xA97F), (0xD7B0, 0xD7FF)):
        for cp in range(lo, hi + 1):
            name = unicodedata.name(chr(cp), "")
            if not name.startswith("HANGUL ") or "FILLER" in name:
                continue
            kind, _, rest = name[len("HANGUL "):].partition(" ")
            parts = rest.split("-")
            try:
                if kind in ("CHOSEONG", "JONGSEONG"):
                    seq = "".join(consonant(p) for p in parts)
                    tables["CHO" if kind == "CHOSEONG" else "JONG"].append((seq, cp))
                elif kind == "JUNGSEONG":
                    tables["JUNG"].append(("".join(vowel(p) for p in parts), cp))
            except KeyError as e:
                skipped.append(f"U+{cp:04X} {name} ({e})")
    # Compatibility jamo that show a jamo alone.
    compat = []
    for cp in range(0x3131, 0x318F):
        d = unicodedata.normalize("NFKC", chr(cp))
        if len(d) == 1 and d != chr(cp):
            compat.append((ord(d), cp))
    lines = [
        "//! Generated by tools/gen_old_jamo.py from the Unicode Character Database;",
        "//! do not edit. Each conjoining jamo with the letters typed to build it.",
        "",
    ]
    for k, rows in tables.items():
        seen = {}
        for seq, cp in rows:
            seen.setdefault(seq, cp)
        lines.append(f"pub const {k}: &[(&str, char)] = &[")
        lines += [f'    ("{s}", \'\\u{{{c:04X}}}\'),' for s, c in seen.items()]
        lines.append("];")
        lines.append("")
    lines.append("/// (conjoining jamo, compatibility jamo that displays it alone)")
    lines.append("pub const COMPAT: &[(char, char)] = &[")
    lines += [f"    ('\\u{{{a:04X}}}', '\\u{{{b:04X}}}')," for a, b in compat]
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print({k: len(v) for k, v in tables.items()}, "compat", len(compat), file=sys.stderr)
    for s in skipped:
        print("skipped", s, file=sys.stderr)


if __name__ == "__main__":
    main()
